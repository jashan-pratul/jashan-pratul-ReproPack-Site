/**
 * Structured JSON export for the playground.
 *
 * The shape below is the website demo's export format. It is intentionally
 * labelled as such inside the file so nobody mistakes it for a published
 * schema — see the repository README for the extension's own export format.
 */
import { SITE_CONFIG } from "../config/site";
import type { DiagnosticEvent, EventSource, JsonObject, Severity } from "./events";
import type { Finding } from "./redaction";

export interface ExportItem {
  event: DiagnosticEvent;
  displayPayload: JsonObject;
  displayMessage: string;
  findings: Finding[];
}

export interface ExportOptions {
  redactionEnabled: boolean;
  sessionId: string;
  sessionStartedAt: number;
  capacity: number;
  evictedCount: number;
  bufferedCount: number;
  filter: { severities: Severity[]; sources: EventSource[]; query: string };
  now?: number;
}

export interface ExportDocument {
  format: "repropack-site-demo-export";
  formatVersion: 1;
  note: string;
  exportedAt: string;
  session: {
    id: string;
    startedAt: string;
    bufferCapacity: number;
    bufferedEvents: number;
    evictedEvents: number;
  };
  redaction: {
    enabled: boolean;
    method: "heuristic";
    disclaimer: string;
    findingsCount: number;
  };
  filter: ExportOptions["filter"];
  eventCount: number;
  events: Array<{
    id: string;
    seq: number;
    timestamp: string;
    severity: Severity;
    source: EventSource;
    category: string;
    message: string;
    payload: JsonObject;
  }>;
}

export const REDACTION_DISCLAIMER =
  "Heuristic, pattern-based redaction. Best-effort only: it can miss sensitive values and is not a security or compliance guarantee. Review before sharing.";

export function buildExport(items: readonly ExportItem[], opts: ExportOptions): ExportDocument {
  const now = opts.now ?? Date.now();
  return {
    format: "repropack-site-demo-export",
    formatVersion: 1,
    note: `Generated by the ${SITE_CONFIG.name} website playground from simulated demo data.`,
    exportedAt: new Date(now).toISOString(),
    session: {
      id: opts.sessionId,
      startedAt: new Date(opts.sessionStartedAt).toISOString(),
      bufferCapacity: opts.capacity,
      bufferedEvents: opts.bufferedCount,
      evictedEvents: opts.evictedCount,
    },
    redaction: {
      enabled: opts.redactionEnabled,
      method: "heuristic",
      disclaimer: REDACTION_DISCLAIMER,
      findingsCount: opts.redactionEnabled ? items.reduce((n, i) => n + i.findings.length, 0) : 0,
    },
    filter: opts.filter,
    eventCount: items.length,
    events: items.map(({ event, displayPayload, displayMessage }) => ({
      id: event.id,
      seq: event.seq,
      timestamp: new Date(event.ts).toISOString(),
      severity: event.severity,
      source: event.source,
      category: event.category,
      message: displayMessage,
      payload: displayPayload,
    })),
  };
}

export function serializeExport(doc: ExportDocument): string {
  return JSON.stringify(doc, null, 2);
}

export function exportFilename(sessionId: string, now = Date.now()): string {
  const stamp = new Date(now).toISOString().replace(/[:.]/g, "-").replace(/-\d{3}Z$/, "Z");
  return `repropack-${sessionId}-${stamp}.json`;
}
